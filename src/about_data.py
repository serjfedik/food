# Дев-статистика (из git)
# ---------------------------------------------------------------------------

def _git(*args: str) -> str:
    try:
        result = subprocess.run(
            ["git", *args], cwd=REPO_ROOT, capture_output=True, text=True, timeout=5
        )
        return result.stdout.strip()
    except Exception:
        return ""


def dev_stats() -> dict[str, Any]:
    commits_str = _git("rev-list", "--count", "HEAD")
    try:
        commits = int(commits_str) if commits_str else 0
    except ValueError:
        commits = 0

    dates_str = _git("log", "--format=%cs", "HEAD")
    days = len({d for d in dates_str.split() if d})

    last = _git("log", "-1", "--format=%cs %h")
    if not last:
        last = "—"

    sha = _git("rev-parse", "--short=8", "HEAD") or "—"
    version = f"v0.{commits}" if commits else "v0.0"

    return {
        "version": version,
        "commits": commits,
        "days": days,
        "last": last,
        "sha": sha,
    }
